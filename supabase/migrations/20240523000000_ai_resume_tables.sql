-- Migration: AI Resume Tailoring and ATS Optimization Tables

-- Table: jd_analyses
-- Stores Job Descriptions pasted by users
CREATE TABLE jd_analyses (
  id UUID DEFAULT gen_random_uuid() PRIMARY KEY,
  user_id UUID NOT NULL, -- Assuming integration with auth.users
  title TEXT,
  company TEXT,
  role TEXT,
  content TEXT NOT NULL,
  created_at TIMESTAMP WITH TIME ZONE DEFAULT timezone('utc'::text, now()) NOT NULL
);

-- Table: resume_versions
-- Stores tailored duplicates of original resumes
CREATE TABLE resume_versions (
  id UUID DEFAULT gen_random_uuid() PRIMARY KEY,
  parent_id UUID, -- References the original resume ID (if stored in a resumes table)
  user_id UUID NOT NULL,
  title TEXT NOT NULL,
  ats_score INTEGER DEFAULT 0,
  content JSONB NOT NULL,
  created_at TIMESTAMP WITH TIME ZONE DEFAULT timezone('utc'::text, now()) NOT NULL,
  updated_at TIMESTAMP WITH TIME ZONE DEFAULT timezone('utc'::text, now()) NOT NULL
);

-- Table: ai_resume_analysis
-- Stores the ATS Score and Match analysis for a specific Resume against a specific JD
CREATE TABLE ai_resume_analysis (
  id UUID DEFAULT gen_random_uuid() PRIMARY KEY,
  user_id UUID NOT NULL,
  resume_id UUID NOT NULL, -- Could reference resume_versions or the main resumes table
  jd_id UUID REFERENCES jd_analyses(id) ON DELETE CASCADE,
  ats_score INTEGER NOT NULL,
  match_percentage INTEGER NOT NULL,
  missing_keywords TEXT[] DEFAULT '{}',
  strong_areas TEXT[] DEFAULT '{}',
  weak_areas TEXT[] DEFAULT '{}',
  created_at TIMESTAMP WITH TIME ZONE DEFAULT timezone('utc'::text, now()) NOT NULL
);

-- Table: ai_suggestions
-- Stores individual contextual suggestions generated by the AI
CREATE TABLE ai_suggestions (
  id UUID DEFAULT gen_random_uuid() PRIMARY KEY,
  analysis_id UUID REFERENCES ai_resume_analysis(id) ON DELETE CASCADE,
  section TEXT NOT NULL, -- e.g., "experience", "summary", "skills"
  original_text TEXT,
  suggested_text TEXT NOT NULL,
  status TEXT DEFAULT 'pending' CHECK (status IN ('pending', 'applied', 'dismissed')),
  created_at TIMESTAMP WITH TIME ZONE DEFAULT timezone('utc'::text, now()) NOT NULL
);

-- Indexes for performance
CREATE INDEX idx_jd_analyses_user_id ON jd_analyses(user_id);
CREATE INDEX idx_resume_versions_user_id ON resume_versions(user_id);
CREATE INDEX idx_resume_versions_parent_id ON resume_versions(parent_id);
CREATE INDEX idx_ai_resume_analysis_user_id ON ai_resume_analysis(user_id);
CREATE INDEX idx_ai_resume_analysis_resume_id ON ai_resume_analysis(resume_id);
CREATE INDEX idx_ai_resume_analysis_jd_id ON ai_resume_analysis(jd_id);
CREATE INDEX idx_ai_suggestions_analysis_id ON ai_suggestions(analysis_id);

-- Add Row Level Security (RLS)
ALTER TABLE jd_analyses ENABLE ROW LEVEL SECURITY;
ALTER TABLE resume_versions ENABLE ROW LEVEL SECURITY;
ALTER TABLE ai_resume_analysis ENABLE ROW LEVEL SECURITY;
ALTER TABLE ai_suggestions ENABLE ROW LEVEL SECURITY;

-- Basic RLS Policies (Users can only see and manage their own data)
CREATE POLICY "Users can manage their own JD analyses"
  ON jd_analyses
  FOR ALL
  USING (auth.uid() = user_id);

CREATE POLICY "Users can manage their own resume versions"
  ON resume_versions
  FOR ALL
  USING (auth.uid() = user_id);

CREATE POLICY "Users can manage their own AI analyses"
  ON ai_resume_analysis
  FOR ALL
  USING (auth.uid() = user_id);

CREATE POLICY "Users can manage suggestions via analysis owner"
  ON ai_suggestions
  FOR ALL
  USING (
    EXISTS (
      SELECT 1 FROM ai_resume_analysis
      WHERE ai_resume_analysis.id = ai_suggestions.analysis_id
      AND ai_resume_analysis.user_id = auth.uid()
    )
  );
